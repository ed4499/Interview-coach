/**
 * Deterministic, offline stand-in for the AI, used ONLY when INTERVIEW_AI_MODE=test
 * (automated tests, QA walkthroughs, demos without an API key). Scores come from
 * simple keyword heuristics and the UI shows a "Test mode" banner so they are never
 * mistaken for real evaluations.
 */
import { rubricFor } from "../config";
import type { DimensionScore } from "../scoring";
import type { AnswerInput, EvaluationResult, InterviewAI, QuestionContext } from "./types";

const SIGNALS: Record<string, RegExp> = {
  situation: /\b(when|at my|while|during|our team|company|project|context)\b/i,
  task: /\b(responsib|my role|i was asked|goal|needed to|assigned|my job)\b/i,
  action: /\b(i (configured|checked|built|wrote|led|analy[sz]ed|reviewed|escalated|implemented|created|tested|fixed|investigated|decided))\b/i,
  result: /\b(result|reduced|improved|increased|resolved|outcome|saved|%|percent|learned)\b/i,
  accuracy: /\b(because|protocol|configur|log|metric|policy|encrypt|access|model|query|test)\w*/i,
  reasoning: /\b(because|tradeoff|trade-off|therefore|so that|depends|instead)\b/i,
  completeness: /\b(also|additionally|first|second|finally|then)\b/i,
  communication: /[.!?]\s+[A-Z]/,
  problem_framing: /\b(first|scope|impact|assess|identify|check|symptom)\b/i,
  proposed_actions: /\b(i would|then|next|isolate|restart|roll back|rollback|patch|configure)\b/i,
  validation_and_outcome: /\b(verify|validate|confirm|monitor|test|metric)\w*/i,
  communication_and_risk: /\b(communicat|escalat|stakeholder|risk|notify|ticket|change)\w*/i,
};

function words(s: string) {
  return s.trim().split(/\s+/).filter(Boolean).length;
}

function firstSentence(s: string) {
  const m = s.trim().match(/^[^.!?]{1,160}[.!?]?/);
  return m ? m[0] : s.slice(0, 160);
}

export class TestModeInterviewAI implements InterviewAI {
  readonly name = "test-mode";

  async decideFollowup(q: QuestionContext, _c: unknown, a: AnswerInput) {
    if (words(a.responseText) < 40) {
      return { needs_followup: true, trigger: "vague outcome", followup_question: q.followup_templates[0] };
    }
    return { needs_followup: false, trigger: null, followup_question: null };
  }

  async evaluate(q: QuestionContext, _c: unknown, a: AnswerInput): Promise<EvaluationResult> {
    const text = `${a.responseText}\n${a.followupResponseText ?? ""}`;
    const lengthCredit = Math.min(40, Math.round(words(text) / 3));
    const dimensions: Record<string, DimensionScore> = {};
    const missing: string[] = [];
    for (const d of rubricFor(q.category)) {
      const hit = SIGNALS[d.key]?.test(text) ?? false;
      const score = words(text) === 0 ? 0 : Math.min(100, lengthCredit + (hit ? 50 : 10));
      if (!hit) missing.push(`${d.label}: not clearly addressed`);
      dimensions[d.key] = {
        score,
        evidence: hit ? firstSentence(text) : "Not addressed in the response.",
        gap: hit ? null : `${d.label} is not clearly addressed.`,
        actionable_tip: `Make your ${d.label.toLowerCase()} explicit.`,
      };
    }
    return {
      dimensions,
      strengths: missing.length < rubricFor(q.category).length ? ["Addresses part of the rubric (test-mode heuristic)."] : [],
      improvements: missing.map((m) => `Strengthen ${m.split(":")[0].toLowerCase()}.`),
      missing_components: missing,
      answer_outline: rubricFor(q.category)
        .map((d) => `- **${d.label}:** [your ${d.label.toLowerCase()} details]`)
        .join("\n"),
      confidence: "low",
    };
  }

  async summarize(_c: unknown, qs: Parameters<InterviewAI["summarize"]>[1]) {
    const dims = new Map<string, { total: number; n: number; ids: string[] }>();
    for (const q of qs) {
      for (const [k, v] of Object.entries(q.dimensions)) {
        const e = dims.get(k) ?? { total: 0, n: 0, ids: [] };
        e.total += v.score;
        e.n += 1;
        if (v.score < 60) e.ids.push(q.question_id);
        dims.set(k, e);
      }
    }
    const weakest = [...dims.entries()].sort((a, b) => a[1].total / a[1].n - b[1].total / b[1].n).slice(0, 3);
    while (weakest.length < 3) weakest.push(["general", { total: 0, n: 1, ids: [] }]);
    return {
      coaching_actions: weakest.map(([k, v], i) => ({
        priority: i + 1,
        title: `Practice ${k.replace(/_/g, " ")}`,
        detail: `Your lowest average dimension was ${k.replace(/_/g, " ")}. Rehearse answers that address it explicitly.`,
        related_question_ids: v.ids.slice(0, 5),
      })),
      overall_notes: "Test-mode summary generated by heuristics, not by the AI coach.",
    };
  }

  async compare(_q: QuestionContext, _c: unknown, prev: { response: string; score: number }, rev: { response: string; score: number }) {
    const dw = words(rev.response) - words(prev.response);
    return {
      summary: `The revised answer is ${Math.abs(dw)} words ${dw >= 0 ? "longer" : "shorter"} and scored ${Math.round(rev.score - prev.score)} points ${rev.score >= prev.score ? "higher" : "lower"}.`,
      specific_changes: [`Word count changed by ${dw}.`],
      remaining_gaps: [],
    };
  }
}
